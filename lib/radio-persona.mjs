/** 跨时段：先打个招呼再换话题（例如 17 点从"下午茶"切到"下班路上"） */
export function slotChangeTask(slot, topic, hook) {
  return (
    `时间来到了${slot.label}（${slot.subtitle}）。先用一句话跟大家打个${slot.label}的招呼，` +
    `说一句和这个时间有关的话，然后自然地引出新话题「${topic}」${hook ? `，可以用这个引子：${hook}` : ''}，` +
    '最后邀请大家在弹幕里聊。三句左右，不超过 110 个字。'
  );
}

