/** 每次调用都带的现场信息：时间、话题、刚说过的话（避免重复） */
export function radioContext({ now, slot, topic, recentSays = [], wall = [] }) {
  const lines = [`现在是北京时间 ${now}。`];
  if (slot) lines.push(slotPrompt(slot));
  if (topic?.text) lines.push(`当前话题：「${topic.text}」${topic.hook ? `（引子：${topic.hook}）` : ''}。`);
  if (wall.length) lines.push(`观众提议的候选话题：${wall.slice(0, 3).map((w) => `「${w.text}」${w.count}票`).join('、')}。`);
  if (recentSays.length) lines.push(`你刚才说过（别重复）：\n${recentSays.slice(-4).map((s) => `- ${s}`).join('\n')}`);
  return lines.join('\n');
}

